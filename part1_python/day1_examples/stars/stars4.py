"""stars4. 오른쪽 정렬 계단: 별 앞에 공백을 붙인다
" " * 3 은 공백 3칸이다.
실행: python stars4.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. n = 5일 때 줄마다 공백은 몇 칸, 별은 몇 개인지 종이에 적어 보세요.
  Q2. 공백 " "를 "."로 바꾸면 공백이 눈에 보입니다. 직접 해 보세요.

결과:
    *
   **
  ***
 ****
*****
"""
n = 5

for i in range(1, n + 1):
    print(" " * (n - i) + "*" * i)
