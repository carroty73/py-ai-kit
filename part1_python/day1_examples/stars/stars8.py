"""stars8. 마름모: 피라미드 + 역피라미드(맨 윗줄 빼고)
반복문을 두 번 쓴다.
실행: python stars8.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. 두 번째 반복문의 n - 1을 n으로 바꾸면 어떻게 될까요?
  Q2. n을 3으로 바꾸면 모양이 어떻게 될까요?

결과:
    *
   ***
  *****
 *******
*********
 *******
  *****
   ***
    *
"""
n = 5

for i in range(1, n + 1):
    print(" " * (n - i) + "*" * (2 * i - 1))

for i in range(n - 1, 0, -1):
    print(" " * (n - i) + "*" * (2 * i - 1))
