"""stars9. 모래시계: 역피라미드 + 피라미드(맨 윗줄 빼고)
실행: python stars9.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. 두 번째 반복문의 range(2, n + 1)을 range(1, n + 1)로 바꾸면 어떻게 될까요?
  Q2. n을 4로 바꾸면 모양이 어떻게 될까요?

결과:
*********
 *******
  *****
   ***
    *
   ***
  *****
 *******
*********
"""
n = 5

for i in range(n, 0, -1):
    print(" " * (n - i) + "*" * (2 * i - 1))

for i in range(2, n + 1):
    print(" " * (n - i) + "*" * (2 * i - 1))
