"""stars6. 피라미드: 줄마다 별이 2개씩 늘어난다 (1, 3, 5, 7, 9)
별 개수는 2 * i - 1, 앞 공백은 n - i 이다.
실행: python stars6.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. n을 바꿔도 피라미드 모양이 유지되는 이유를 생각해 보세요.
  Q2. 2 * i - 1을 2 * i로 바꾸면 어떤 모양이 될까요?
  Q3. 공백 " "를 "."로 바꿔서 공백 칸 수를 눈으로 확인해 보세요.

결과:
    *
   ***
  *****
 *******
*********
"""
n = 5

for i in range(1, n + 1):
    print(" " * (n - i) + "*" * (2 * i - 1))
