"""6. 입력받기: input
실행: python 06_input.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. 나이에 18, 19를 입력하면 각각 어떤 글이 나올까요? 예상한 뒤 확인해 보세요.
  Q2. 기준을 19에서 20으로 바꿔 보세요.
  Q3. 좋아하는 음식을 input으로 받아 "나도 ___ 좋아해요"를 출력해 보세요.
"""
name = input("이름이 뭐예요? ")
print(name, "님, 환영합니다!")

# input은 항상 '글자'를 돌려준다. 숫자로 쓰려면 int()로 바꿔야 한다.
age = int(input("나이는요? "))
print("내년에는", age + 1, "살이네요.")

if age < 19:
    print("고등학생 이하로군요. 반가워요!")
else:
    print("성인이시군요. 반가워요!")
