"""9. 카운트다운: 거꾸로 세기
range(시작, 끝, 간격): 5에서 시작해 1까지, 간격 -1씩 줄어든다. (끝 숫자 0은 포함되지 않는다)
실행: python 09_countdown.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. 5를 10으로 바꾸면 어떻게 될까요?
  Q2. range(5, 0, -1)을 range(5, 0, -2)로 바꾸면 무엇이 출력될까요?
  Q3. print("발사!")를 for 안쪽(들여쓰기 안)으로 옮기면 어떻게 될까요?
"""
