"""12. 반복문: 같은 일을 여러 번 시키기
실행: python 12_loop.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. range(5)를 range(10)으로 바꿔 보세요.
  Q2. hp = hp - 20을 hp = hp - 10으로 바꾸면 "남은 체력"이 몇 번 출력될까요?
  Q3. hp의 시작값을 50에서 100으로 바꾸면 "남은 체력"이 몇 번 출력될까요?
"""
# for: 정해진 횟수만큼 반복 (range(5)는 0, 1, 2, 3, 4)
for i in range(5):
    print("공격!", i)

print("-----")

# while: 조건이 참인 동안 계속 반복
hp = 50
while hp > 0:
    print("남은 체력:", hp)
    hp = hp - 20

print("쓰러졌다!")
