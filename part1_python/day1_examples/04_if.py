"""4. 조건문 if: 상황에 따라 다르게 행동하기
실행: python 04_if.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. hp를 80, 30, 0으로 바꿨을 때 각각 어떤 글이 나올까요? 예상한 뒤 확인해 보세요.
  Q2. hp = 50이면 어떤 글이 나올까요? 왜 그럴까요?
  Q3. hp > 50을 hp >= 50으로 바꾸고 hp = 50으로 실행하면 어떻게 달라질까요?
"""
hp = 30

if hp > 50:
    print("체력이 넉넉하다. 계속 싸우자!")
elif hp > 0:
    print("체력이 위험하다! 물약을 마시자.")
else:
    print("쓰러졌다... 게임 오버")

# 주의: if 아랫줄은 공백 4칸 들여써야 한다. 이것이 파이썬의 규칙이다.
