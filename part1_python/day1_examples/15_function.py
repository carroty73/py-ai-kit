"""15. 함수: 자주 하는 일에 이름을 붙여 두기
함수 없이 하면 얼마나 불편한지 먼저 보고, 함수로 바꿔 본다.
실행: python 15_function.py

퀴즈: 먼저 결과를 예상한 뒤, 코드를 바꿔 실행해서 확인해 보세요.
  Q1. "의 공격!"을 "의 필살기!"로 바꾸려면 방법 1은 몇 줄을 고쳐야 할까요? 방법 2는요?
  Q2. attack("궁수", 25)를 추가해 보세요.
  Q3. double(21)을 double(5)로 바꾸면 무엇이 나올까요?
  Q4. 3배를 돌려주는 triple 함수를 직접 만들어 보세요.
"""
# 방법 1: 함수 없이 무식하게 (같은 출력을 매번 직접 쓴다)
print("용사", "의 공격! 피해", 15)
print("마법사", "의 공격! 피해", 40)
print("용사", "의 공격! 피해", 20)

print()

# 방법 2: def로 한 번 만들어 두고 이름만 부른다. 결과는 똑같다.
def attack(name, power):
    print(name, "의 공격! 피해", power)


attack("용사", 15)
attack("마법사", 40)
attack("용사", 20)

print()


# 값을 돌려주는 함수
def double(n):
    return n * 2


print(double(21))
